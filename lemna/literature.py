def apa(key):
    """APA 7 reference string."""
    if key in OTHER_SOURCES:
        return OTHER_SOURCES[key]
    authors, year, title, journal, volume, issue, pages, doi = LITERATURE[key]
    vol = f"{volume}({issue})" if issue else volume
    return f"{authors} ({year}). {title}. {journal}, {vol}, {pages}. https://doi.org/{doi}"


def c(*keys):
    """In-text citation such as '(Kalčíková vd., 2017; Rozman vd., 2022)'."""
    return "(" + "; ".join(CITE[k] for k in keys) + ")"


def sort_key(key):
    return apa(key).lower()


